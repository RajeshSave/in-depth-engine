"""
genai.py -- Layer 3: executive development report.
Calls Gemini / Claude / ChatGPT when an API key is supplied; otherwise (or if the call
fails for any reason) falls back to a local template report so the app never crashes.
"""
import html

import pandas as pd

from ml_engine import COMPETENCY_COLS

PROVIDERS = ["Google Gemini", "Anthropic Claude", "OpenAI ChatGPT"]
# Model names live here so they are easy to update when providers retire models.
MODELS = {"Google Gemini": "gemini-2.0-flash", "Anthropic Claude": "claude-sonnet-5-5", "OpenAI ChatGPT": "gpt-4o-mini"}


def build_prompt(c: dict, ctx: dict) -> str:
    return f"""You are a Senior Talent Management Consultant advising a Financial Services firm's Executive Committee on succession planning. The firm uses a 3-5 year succession framework where Performance data is an eligibility GATE (not the deciding factor) and Assessment/Potential data is the primary readiness driver.

Write an EXECUTIVE DEVELOPMENT RECOMMENDATION with exactly these sections: (1) Executive Summary, (2) Key Strengths, (3) Development Areas, (4) Recommended Development Actions (next 12 months), (5) Succession Timeline Recommendation. Under 350 words, for a CHRO / Executive Committee audience. Do not just repeat the raw scores.

CANDIDATE
- Name: {c['Full_Name']} | {c['Job_Level']} | {c['Business_Unit']} - {c.get('Sub_Function', '')}
- Experience: {c['Years_of_Experience']} yrs | Tenure: {c['Years_at_Company']} yrs | Avg performance: {c['Avg_Performance_Rating']}/5
- Analytical {c['Analytical_Test_Score']} | Risk & Compliance {c['Risk_Compliance_Score']} | Leadership {c['Leadership_Potential_Score']} | Communication {c['Communication_Score']} | Client Mgmt {c['Client_Management_Score']} | Engagement {c['Engagement_Score']}
- Career velocity: {c['Career_Velocity_Score']} promotions per tenure year
- Rule-based flag: {ctx['layer1_flag']} | Talent cluster: {ctx['cluster']} | Retention risk: {ctx['retention']}
- Readiness framework ({ctx['horizon']}, {ctx['perf_pct']}% Performance / {100 - ctx['perf_pct']}% Assessment): Performance Component {c['Performance_Component']}, Assessment Component {c['Assessment_Component']}, Readiness Score {c['Succession_Readiness_Score']}, Gate: {c['Gate_Status']}"""


def mock_report(c: dict, ctx: dict) -> str:
    scores = {k: float(c[k]) for k in COMPETENCY_COLS if pd.notna(c.get(k))}
    ranked = sorted(scores, key=scores.get, reverse=True)
    strengths = ", ".join(k.replace("_Score", "").replace("_", " ") for k in ranked[:3])
    weak = ranked[-1]
    weak_txt = weak.replace("_Score", "").replace("_", " ")
    if c["Gate_Status"] != "Eligible":
        timeline = "Not yet eligible - below the performance gate for this horizon"
    elif ctx["layer1_flag"] == "Ready for Leadership Track":
        timeline = "Ready now (0-12 months)"
    elif ctx["layer1_flag"] == "Fast-Track Talent" or float(c["Succession_Readiness_Score"]) >= 75:
        timeline = "1-2 years"
    elif str(ctx["retention"]).startswith("High"):
        timeline = "Retention intervention required before succession planning"
    else:
        timeline = "3-5 years"
    return f"""**EXECUTIVE SUMMARY**
{c['Full_Name']} is a {c['Job_Level']} in {c['Business_Unit']} with {c['Years_of_Experience']} years of experience and an average performance rating of {c['Avg_Performance_Rating']}/5. The talent segmentation places them in the '{ctx['cluster']}' cluster and the rule screen returns '{ctx['layer1_flag']}'. Under the {ctx['horizon']} weighting ({ctx['perf_pct']}% Performance / {100 - ctx['perf_pct']}% Assessment) the Succession Readiness Score is {c['Succession_Readiness_Score']}/100 (Performance {c['Performance_Component']}, Assessment {c['Assessment_Component']}); gate status: **{c['Gate_Status']}**.

**KEY STRENGTHS**
Highest-scoring competencies: {strengths}.

**DEVELOPMENT AREAS**
Largest relative gap: {weak_txt} ({scores[weak]:.0f}/100).

**RECOMMENDED DEVELOPMENT ACTIONS (NEXT 12 MONTHS)**
1. Targeted coaching or a stretch assignment addressing {weak_txt}.
2. Mentorship pairing with a senior leader in {c['Business_Unit']}.
3. Enrol in the High-Potential Leadership Programme if not already engaged.
4. Quarterly calibration check-in against risk and compliance benchmarks.

**SUCCESSION TIMELINE RECOMMENDATION**
{timeline}. Predicted retention risk: {ctx['retention']}.

*Generated by the local template engine (no live API key / call unavailable).*"""


def _call_api(provider: str, api_key: str, prompt: str) -> str:
    import requests
    model = MODELS[provider]
    if provider == "Google Gemini":
        r = requests.post(f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
                          params={"key": api_key}, json={"contents": [{"parts": [{"text": prompt}]}]}, timeout=30)
        r.raise_for_status()
        return r.json()["candidates"][0]["content"]["parts"][0]["text"]
    if provider == "Anthropic Claude":
        r = requests.post("https://api.anthropic.com/v1/messages",
                          headers={"x-api-key": api_key, "anthropic-version": "2023-06-01"},
                          json={"model": model, "max_tokens": 900, "messages": [{"role": "user", "content": prompt}]}, timeout=30)
        r.raise_for_status()
        return r.json()["content"][0]["text"]
    r = requests.post("https://api.openai.com/v1/chat/completions", headers={"Authorization": f"Bearer {api_key}"},
                      json={"model": model, "max_tokens": 900, "messages": [{"role": "user", "content": prompt}]}, timeout=30)
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"]


def generate_report(provider: str, api_key: str, candidate: dict, ctx: dict):
    """Returns (markdown_text, source_description). Never raises."""
    if api_key and api_key.strip():
        try:
            text = _call_api(provider, api_key.strip(), build_prompt(candidate, ctx))
            if text and text.strip():
                return text, f"Live API - {provider} ({MODELS[provider]})"
        except Exception as e:  # network, auth, quota, bad response ...
            return mock_report(candidate, ctx), f"Local fallback (live call to {provider} failed: {type(e).__name__})"
    return mock_report(candidate, ctx), "Local template engine (no API key supplied)"


def report_to_html(title: str, markdown_text: str) -> str:
    body = html.escape(markdown_text)
    import re
    body = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", body).replace("\n", "<br>")
    return (f"<html><head><meta charset='utf-8'><title>{html.escape(title)}</title></head>"
            "<body style='font-family:Arial,sans-serif;max-width:800px;margin:30px auto;color:#0B2540;'>"
            f"<h1 style='border-bottom:3px solid #C9A227;'>{html.escape(title)}</h1>{body}</body></html>")
